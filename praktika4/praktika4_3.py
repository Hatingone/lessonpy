num = int(input('Введите число четырехзначное число '))
tsachi = num // 1000
sotni  = (num // 100) % 10
ten = (num // 10) % 10
edin = num % 10
print('Цифра в позиции тысяч равна = ', tsachi)
print('Цифра в позиции сотен равна = ', sotni)
print('Цифра в позиции десятков равна = ', ten)
print('Цифра в позиции единиц равна = ', edin)
